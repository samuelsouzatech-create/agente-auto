-- Migração 21: Instagram (Maratona 4, IG1). Número reservado desde o plano mestre (seção 17).
-- Só ACRESCENTA (coluna nova opcional e tabela nova): nenhum dado existente muda ou some.
-- Pensada para o IG1, o IG2 e o IG3 de uma vez (para não precisar de outra migração).

-- IG1 (I3): id da mensagem NO CANAL. O Léo grava o id de cada bolha que manda pelo Instagram; o
-- eco que chega com esse id é dele mesmo e é descartado (sem isso, cada resposta do Léo viraria um
-- falso "o vendedor assumiu"). Vários ids separados por espaço (uma resposta = várias bolhas).
ALTER TABLE mensagens ADD COLUMN IF NOT EXISTS id_externo TEXT;
CREATE INDEX IF NOT EXISTS idx_mensagens_id_externo ON mensagens (loja_id, canal, lead_id)
    WHERE id_externo IS NOT NULL;

-- IG1 (I5): de onde veio o lead (anuncio, perfil, comentario, direto), para a aba Leads.
-- origem_detalhe: o id do post ou do anúncio (nunca dado pessoal).
ALTER TABLE leads ADD COLUMN IF NOT EXISTS origem TEXT;
ALTER TABLE leads ADD COLUMN IF NOT EXISTS origem_detalhe TEXT;

-- IG3: telefone que o lead do Instagram passou e quando (o "mesmo cliente" no WhatsApp vale
-- por um prazo a partir daqui).
ALTER TABLE leads ADD COLUMN IF NOT EXISTS telefone TEXT;
ALTER TABLE leads ADD COLUMN IF NOT EXISTS telefone_em TEXT;

-- IG2: cada comentário tratado (dedup por comment_id, uma resposta privada por comentário).
-- Não guarda o texto do comentário (LGPD: só o necessário).
CREATE TABLE IF NOT EXISTS instagram_comentarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id BIGINT NOT NULL,
    comment_id TEXT NOT NULL,
    media_id TEXT,
    ad_id TEXT,
    lead_id TEXT,                          -- ig:<id de quem comentou>
    origem TEXT NOT NULL DEFAULT 'comentario',   -- comentario | anuncio
    estado TEXT NOT NULL,                  -- respondido | desligado | propria_loja | fora_do_prazo | falhou
    caminho TEXT,                          -- IG2, Opção B: item | vendido | generico
    item_id BIGINT,                        -- o item do catálogo citado no post (se achou um)
    resposta_publica TEXT,                 -- respondida | desligada | falhou | NULL
    criado_em TEXT DEFAULT agora_texto(),
    UNIQUE (loja_id, comment_id)
);
CREATE INDEX IF NOT EXISTS idx_instagram_comentarios_lead ON instagram_comentarios (loja_id, lead_id);

-- IG2: legenda de cada post, guardada por um tempo (o Léo não pergunta à Meta a cada comentário).
CREATE TABLE IF NOT EXISTS instagram_legendas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id BIGINT NOT NULL,
    media_id TEXT NOT NULL,
    legenda TEXT,
    lida_em TEXT DEFAULT agora_texto(),
    UNIQUE (loja_id, media_id)
);

-- IG3: duas conversas que são o MESMO cliente (ex.: o lead do Instagram que passou o telefone e
-- depois escreveu no WhatsApp). Sempre dentro da MESMA loja.
CREATE TABLE IF NOT EXISTS clientes_vinculados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id BIGINT NOT NULL,
    lead_principal TEXT NOT NULL,          -- a conversa que aparece no painel (a primeira)
    lead_vinculado TEXT NOT NULL,          -- a outra conversa do mesmo cliente
    canal_vinculado TEXT NOT NULL,
    motivo TEXT NOT NULL DEFAULT 'telefone',
    criado_em TEXT DEFAULT agora_texto(),
    UNIQUE (loja_id, lead_vinculado)
);
CREATE INDEX IF NOT EXISTS idx_clientes_vinculados_principal ON clientes_vinculados (loja_id, lead_principal);

-- IG3 (I6): pedidos de exclusão de dados (o código que a Meta mostra à pessoa). Sem dado pessoal:
-- só um resumo (hash) de quem pediu.
CREATE TABLE IF NOT EXISTS pedidos_exclusao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id BIGINT,
    codigo TEXT NOT NULL UNIQUE,
    resumo_do_pedido TEXT NOT NULL,
    origem TEXT NOT NULL,                  -- meta | painel
    linhas_apagadas BIGINT NOT NULL DEFAULT 0,
    criado_em TEXT DEFAULT agora_texto()
);
