-- =====================================================================
-- Migração-base do PostgreSQL (Maratona Postgres, PG1).
-- Equivale ao banco SQLite inteiro até a versão 20 (migrações 1 a 17, 19 e 20; a 18 nunca
-- existiu). Fica registrada como versão 20 em migracoes_aplicadas. A próxima migração usa o
-- próximo número livre (a 21 continua reservada ao Instagram).
--
-- Escolhas para o banco se comportar igual ao SQLite (detalhes em docs/postgres.md):
-- - Datas e horários continuam TEXTO no formato "AAAA-MM-DD HH:MM:SS" em UTC (como o código
--   sempre gravou e compara). agora_texto() faz o papel do CURRENT_TIMESTAMP do SQLite.
-- - Sem chaves estrangeiras obrigatórias (o SQLite não conferia; mudar isso é outro bloco).
-- - O e-mail de login é único sem diferença de maiúsculas (índice em lower(email)).
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS unaccent;

-- Data e hora de agora, em UTC, no mesmo texto do SQLite.
CREATE OR REPLACE FUNCTION agora_texto() RETURNS text LANGUAGE sql VOLATILE AS
$$ SELECT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;

-- Busca sem acento ("Doblò" acha "doblo"). No SQLite era uma função em Python.
CREATE OR REPLACE FUNCTION sem_acento(texto text) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS
$$ SELECT public.unaccent('public.unaccent'::regdictionary, texto) $$;

-- Celular brasileiro normalizado ("5581999998888") ou vazio. Mesma regra de
-- app/telefone.normalizar_telefone_br (no SQLite era a própria função em Python).
CREATE OR REPLACE FUNCTION fone_br(texto text) RETURNS text LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE
    d text := ltrim(regexp_replace(coalesce(texto, ''), '[^0-9]', '', 'g'), '0');
    ddd text;
    numero text;
BEGIN
    IF d LIKE '55%' AND length(d) IN (12, 13) THEN
        d := substr(d, 3);
    END IF;
    IF length(d) NOT IN (10, 11) THEN
        RETURN '';
    END IF;
    ddd := substr(d, 1, 2);
    numero := substr(d, 3);
    IF position('0' in ddd) > 0 THEN
        RETURN '';
    END IF;
    IF length(numero) = 9 THEN
        IF left(numero, 1) <> '9' THEN
            RETURN '';
        END IF;
    ELSIF left(numero, 1) IN ('6', '7', '8', '9') THEN
        numero := '9' || numero;
    ELSE
        RETURN '';
    END IF;
    RETURN '55' || ddd || numero;
END
$$;

-- round(x, casas) com número decimal comum (o PostgreSQL só tem essa conta para "numeric").
CREATE OR REPLACE FUNCTION round(valor double precision, casas integer) RETURNS double precision
LANGUAGE sql IMMUTABLE AS $$ SELECT round(valor::numeric, casas)::double precision $$;

