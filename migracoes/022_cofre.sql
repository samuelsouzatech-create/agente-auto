-- Migração 22: cofre dos tokens dos canais (Maratona Segurança, SE2). Próximo número livre depois
-- da 21 (Instagram). Só ACRESCENTA uma tabela nova: nenhum dado existente muda ou some.
--
-- O token de cada canal de cada loja fica CIFRADO (AES-256-GCM, app/cofre.py). A chave mestra fica
-- só no .env (LEO_CHAVE_MESTRA), nunca aqui. O token_ref antigo da tabela canais continua valendo
-- como reserva enquanto a loja não tiver o token no cofre.
CREATE TABLE IF NOT EXISTS cofre_credenciais (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loja_id BIGINT NOT NULL,
    tipo_canal TEXT NOT NULL CHECK (tipo_canal IN ('whatsapp', 'instagram', 'telegram')),
    conta TEXT NOT NULL,                   -- o id_externo do canal (número, conta ou bot)
    token_cifrado TEXT NOT NULL,           -- "v1:" + base64(nonce + texto cifrado)
    chave_id TEXT NOT NULL,                -- resumo da chave que cifrou (não revela a chave)
    criado_em TEXT NOT NULL DEFAULT agora_texto(),
    atualizado_em TEXT NOT NULL DEFAULT agora_texto(),
    UNIQUE (loja_id, tipo_canal, conta)
);
